// Regenerate the file:// fallback payloads from the verbatim upstream dictionaries.
//
//   node tools/build-dictionaries.mjs
//
// browsers refuse fetch()/XHR of local files, so opening index.html by
// double-click cannot read dictionaries/*.txt. For each .txt we emit a .js that
// hands the *identical* text to the game through a global. The .txt files stay
// the source of truth (byte-identical to logoth80/Hangman); never edit the .js.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

const DICTIONARIES = [
  { file: "pruned_polish.txt", key: "polish" },
  { file: "pruned_english.txt", key: "english" },
];

for (const { file, key } of DICTIONARIES) {
  const source = path.join(root, "dictionaries", file);
  const target = path.join(root, "dictionaries", file.replace(/\.txt$/, ".js"));
  const text = await readFile(source, "utf8");

  const header =
    `/* Generated by tools/build-dictionaries.mjs — do not edit.\n` +
    `   Verbatim contents of dictionaries/${file} (${Buffer.byteLength(text, "utf8")} bytes),\n` +
    `   kept as one string so the game can boot straight from index.html. */\n`;
  const body =
    `(function (root) {\n` +
    `  var store = root.HM_DICT_RAW || (root.HM_DICT_RAW = {});\n` +
    `  store[${JSON.stringify(key)}] = ${JSON.stringify(text)};\n` +
    `})(typeof globalThis !== "undefined" ? globalThis : this);\n`;

  await writeFile(target, header + body, "utf8");
  console.log(
    `${file} -> ${path.basename(target)}  ${text.split("\n").length} lines -> ${(Buffer.byteLength(header + body, "utf8") / 1024).toFixed(0)} KB`,
  );
}
